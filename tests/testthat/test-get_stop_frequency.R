test_that("outputs a data.table with adequate columns' classes", {
  check_output <- function(frequency, by_route = FALSE, direction = TRUE) {
    expected_cols <- c(
      "stop_id",
      if (by_route) "route_id",
      if (by_route && direction) "direction_id",
      "service_id",
      "departures",
      "mean_headway"
    )
    expect_s3_class(frequency, "data.table")
    expect_identical(names(frequency), expected_cols)
    expect_type(frequency$stop_id, "character")
    expect_type(frequency$service_id, "character")
    expect_type(frequency$departures, "integer")
    expect_type(frequency$mean_headway, "double")
    if (by_route) expect_type(frequency$route_id, "character")
    if (by_route && direction) expect_type(frequency$direction_id, "integer")
  }

  for (by_route in c(FALSE, TRUE)) {
    check_output(tester(by_route = by_route), by_route)
    check_output(tester(stop_id = character(0), by_route = by_route), by_route)
    expect_warning(frequency <- tester(stop_id = "ola", by_route = by_route))
    check_output(frequency, by_route)
  }

  expect_identical(nrow(tester(stop_id = character(0))), 0L)

  # direction_id is not included if it's not present in 'trips'

  ggl_frequency <- tester(
    ggl_gtfs,
    by_route = TRUE,
    from = "00:00:00",
    to = "30:00:00"
  )
  check_output(ggl_frequency, by_route = TRUE, direction = FALSE)
})

test_that("calculates the frequency of the correct stop_ids", {
  frequency <- tester(from = "00:00:00", to = "30:00:00")
  expect_true(all(frequency$stop_id %chin% gtfs$stop_times$stop_id))

  frequency <- tester(stop_id = c("18848", "18960"))
  expect_setequal(frequency$stop_id, c("18848", "18960"))
})

test_that("calculates frequency correctly in a hand-built feed", {
  expect_equal(
    tester(hand_gtfs, from = "06:00:00", to = "10:00:00"),
    data.table::data.table(
      stop_id = c("A", "B", "C"),
      service_id = "s",
      departures = c(7L, 7L, 2L),
      mean_headway = 240 / c(7, 7, 2),
      key = c("stop_id", "service_id")
    )
  )

  expect_equal(
    tester(hand_gtfs, by_route = TRUE, from = "06:00:00", to = "10:00:00"),
    data.table::data.table(
      stop_id = c("A", "A", "B", "B", "C"),
      route_id = c("r1", "r2", "r1", "r3", "r3"),
      direction_id = 0L,
      service_id = "s",
      departures = c(5L, 2L, 5L, 2L, 2L),
      mean_headway = 240 / c(5, 2, 5, 2, 2),
      key = c("stop_id", "route_id", "direction_id", "service_id")
    )
  )

  # the departures of trips listed in 'frequencies' are shifted from the trip's
  # first departure, even when its first stop is not specified: "freq" departs
  # from B at 06:05, 06:15 and 06:25

  frequency <- tester(hand_gtfs, "B", from = "06:01:00", to = "06:09:00")
  expect_identical(frequency$departures, 1L)

  frequency <- tester(hand_gtfs, "B", from = "06:00:00", to = "07:00:00")
  expect_identical(frequency$departures, 3L)

  # the last stop of a trip is never counted

  frequency <- tester(hand_gtfs, "C", from = "06:00:00", to = "09:05:00")
  expect_identical(nrow(frequency), 0L)

  # regression guard: the results don't depend on data.table's GForce
  # optimisation (without it, max() and min() of groups without non-missing
  # values return -Inf/Inf with a warning)

  old_optimize <- options(datatable.optimize = 0L)
  on.exit(options(old_optimize), add = TRUE)
  expect_identical(
    tester(
      hand_gtfs,
      by_route = TRUE,
      from = "06:00:00",
      to = "10:00:00"
    )$departures,
    c(5L, 2L, 5L, 2L, 2L)
  )
  expect_identical(
    tester(hand_gtfs, from = "06:00:00", to = "10:00:00")$departures,
    c(7L, 7L, 2L)
  )
})

