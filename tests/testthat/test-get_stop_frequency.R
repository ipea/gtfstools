spo_path <- system.file("extdata/spo_gtfs.zip", package = "gtfstools")
ggl_path <- system.file("extdata/ggl_gtfs.zip", package = "gtfstools")
gtfs <- read_gtfs(spo_path)
ggl_gtfs <- read_gtfs(ggl_path)

tester <- function(gtfs = get("gtfs", envir = parent.frame()),
                   stop_id = NULL,
                   by_route = FALSE,
                   from = "07:00:00",
                   to = "09:00:00") {
  get_stop_frequency(gtfs, stop_id, by_route, from, to)
}

# small hand-built feed, whose expected results are listed in the tests below:
# - "freq" is listed in 'frequencies' and departs at 06:00, 06:10, 06:20,
#   07:00 and 07:10, visiting A at +0 min, B at +5 min and C (its last stop) at
#   +10 min;
# - "loop" visits A twice (08:00 and 08:20), B with a blank time and ends at C;
# - "single" has a single stop, which is therefore its last stop;
# - "na_seq" visits B at 09:00, C at 09:10 (with an NA stop_sequence) and ends
#   at A;
# - "all_na_seq" has only NA stop_sequences, so it has no last stop: it visits
#   B at 09:30 and C at 09:40;
# - "orphan" is listed in 'stop_times', but not in 'trips'

hand_gtfs <- read_gtfs(spo_path)
hand_gtfs$trips <- data.table::data.table(
  trip_id = c("freq", "loop", "single", "na_seq", "all_na_seq"),
  route_id = c("r1", "r2", "r2", "r3", "r3"),
  service_id = "s",
  direction_id = c(0L, 0L, 1L, 0L, 0L)
)
hand_gtfs$stop_times <- data.table::data.table(
  trip_id = c(
    rep("freq", 3),
    rep("loop", 4),
    "single",
    rep("na_seq", 3),
    rep("all_na_seq", 2),
    rep("orphan", 2)
  ),
  stop_id = c(
    "A", "B", "C",
    "A", "B", "A", "C",
    "A",
    "B", "C", "A",
    "B", "C",
    "A", "B"
  ),
  stop_sequence = c(1:3, 1:4, 1L, 1L, NA, 3L, NA, NA, 1:2),
  departure_time = c(
    "10:00:00", "10:05:00", "10:10:00",
    "08:00:00", "", "08:20:00", "08:30:00",
    "08:00:00",
    "09:00:00", "09:10:00", "09:20:00",
    "09:30:00", "09:40:00",
    "08:00:00", "08:10:00"
  )
)
hand_gtfs$stop_times[, arrival_time := departure_time]
hand_gtfs$frequencies <- data.table::data.table(
  trip_id = "freq",
  start_time = c("06:00:00", "07:00:00"),
  end_time = c("06:30:00", "07:20:00"),
  headway_secs = 600L
)

# mixed feed built from spo: trips listed in 'frequencies' and scheduled trips
# (two trips have their 'frequencies' entries removed), one scheduled trip with
# blank times, trips with NA direction_id and two service_ids

mixed_gtfs <- read_gtfs(spo_path)
scheduled_trips <- c("CPTM L07-1", "2002-10-0")
mixed_gtfs$frequencies <- mixed_gtfs$frequencies[
  ! trip_id %chin% scheduled_trips
]

blank_trip <- mixed_gtfs$trips[trip_id == "CPTM L07-1"]
blank_trip[, trip_id := "blank_trip"]
mixed_gtfs$trips <- rbind(mixed_gtfs$trips, blank_trip)

blank_stop_times <- mixed_gtfs$stop_times[trip_id == "CPTM L07-1"]
blank_stop_times[
  ,
  `:=`(trip_id = "blank_trip", arrival_time = "", departure_time = "")
]
mixed_gtfs$stop_times <- rbind(mixed_gtfs$stop_times, blank_stop_times)

mixed_gtfs$trips[
  trip_id %chin% c("CPTM L08-1", "2105-10-1"),
  direction_id := NA
]

# expected number of departures, based on the stop_times table generated by
# frequencies_to_stop_times(), excluding the last stop of each trip and blank
# departure times

expanded_gtfs <- frequencies_to_stop_times(mixed_gtfs)
expanded_departures <- expanded_gtfs$stop_times[
  ,
  .(
    trip_id,
    stop_id,
    stop_sequence,
    departure_secs = string_to_seconds(departure_time)
  )
]
expanded_departures[, last_seq := max(stop_sequence), by = trip_id]
expanded_departures <- expanded_departures[
  stop_sequence != last_seq & !is.na(departure_secs)
]
expanded_departures <- expanded_gtfs$trips[
  expanded_departures,
  on = "trip_id",
  nomatch = NULL
]

expected_frequency <- function(from, to, by_route) {
  from_secs <- string_to_seconds(from)
  to_secs <- string_to_seconds(to)

  group_cols <- c("stop_id", "service_id")
  if (by_route) {
    group_cols <- c("stop_id", "route_id", "direction_id", "service_id")
  }

  expected <- expanded_departures[
    departure_secs >= from_secs & departure_secs < to_secs,
    .(departures = .N),
    keyby = group_cols
  ]
  expected[, mean_headway := (to_secs - from_secs) / departures / 60]

  return(expected[])
}


