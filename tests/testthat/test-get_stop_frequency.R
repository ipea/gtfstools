test_that("the window includes departures at 'from', but not at 'to'", {
  frequency <- tester(hand_gtfs, "A", from = "08:00:00", to = "08:20:00")
  expect_identical(frequency$departures, 1L)

  frequency <- tester(hand_gtfs, "A", from = "08:00:00", to = "08:20:01")
  expect_identical(frequency$departures, 2L)
})

test_that("works with feeds without 'frequencies'", {
  # ber doesn't have a 'frequencies' table, so each stop_times entry is a
  # departure, except for the last stop of each trip

  ber_gtfs <- read_gtfs(
    system.file("extdata/ber_gtfs.zip", package = "gtfstools")
  )
  ber_departures <- ber_gtfs$stop_times[
    ,
    .(
      trip_id,
      stop_id,
      stop_sequence,
      departure_secs = string_to_seconds(departure_time)
    )
  ]
  ber_departures[, last_seq := max(stop_sequence), by = trip_id]
  ber_departures <- ber_departures[stop_sequence != last_seq]
  ber_departures <- ber_gtfs$trips[ber_departures, on = "trip_id"]
  expected <- ber_departures[
    departure_secs >= 6 * 3600 & departure_secs < 10 * 3600,
    .(departures = .N),
    keyby = .(stop_id, service_id)
  ]
  expected[, mean_headway := 240 / departures]

  expect_equal(tester(ber_gtfs, from = "06:00:00", to = "10:00:00"), expected)
})

test_that("counts departures after midnight", {
  # ggl's trip departs every 7 minutes from 20:30:00 to 28:00:00, so 10 times
  # between 24:00:00 (included) and 25:10:00 (not included), from both S1 and
  # S3. S6 is its last stop

  ggl_frequency <- tester(ggl_gtfs, from = "24:00:00", to = "25:10:00")
  expect_identical(ggl_frequency$stop_id, c("S1", "S3"))
  expect_identical(ggl_frequency$departures, c(10L, 10L))
  expect_equal(ggl_frequency$mean_headway, c(7, 7))
})

test_that("doesn't change given gtfs", {
  original_gtfs <- read_gtfs(spo_path)
  gtfs <- read_gtfs(spo_path)
